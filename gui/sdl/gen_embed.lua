#!/usr/bin/env luajit
-- @desc 生成把 Lua/二进制资源嵌入 C 的头文件（替代 gen_embed.py）
-- @usage luajit gen_embed.lua -o out.h name=path [name=path ...]
local out, inputs, i = nil, {}, 1
while i <= #arg do
    local a = arg[i]
    if a == "-o" then
        out = arg[i + 1]; i = i + 2
    elseif a == "-h" or a == "--help" then
        print("usage: gen_embed.lua -o out.h name=path [name=path ...]")
        os.exit(0)
    else
        inputs[#inputs + 1] = a; i = i + 1
    end
end
if not out or #inputs == 0 then
    io.stderr:write("usage: gen_embed.lua -o out.h name=path [name=path ...]\n")
    os.exit(2)
end

local pairs_list = {}
for _, item in ipairs(inputs) do
    local name, path = item:match("^([^=]+)=(.+)$")
    if not name then
        io.stderr:write("bad input (want name=path): " .. item .. "\n"); os.exit(2)
    end
    if not name:match("^[%a_][%w_]*$") then
        io.stderr:write("bad C identifier: " .. name .. "\n"); os.exit(2)
    end
    local f = assert(io.open(path, "rb"))
    local data = f:read("*a"); f:close()
    pairs_list[#pairs_list + 1] = { name = name, data = data }
end

local tmp = out .. ".tmp"
local f = assert(io.open(tmp, "wb"))
f:write("/* generated by gen_embed.lua; do not edit */\n")
f:write("#ifndef MYAGENT_EMBED_H\n#define MYAGENT_EMBED_H\n\n")
for _, p in ipairs(pairs_list) do
    local data = p.data
    f:write("static const unsigned char ", p.name, "[] = {\n")
    for i = 1, #data, 16 do
        local bytes = {}
        for j = i, math.min(i + 15, #data) do
            bytes[#bytes + 1] = string.format("0x%02x", data:byte(j))
        end
        f:write("  ", table.concat(bytes, ", "), ",\n")
    end
    f:write("};\n")
    f:write("static const unsigned int ", p.name, "_len = ", tostring(#data), ";\n\n")
end
f:write("#endif\n")
f:close()
assert(os.rename(tmp, out))
