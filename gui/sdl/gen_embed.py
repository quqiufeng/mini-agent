#!/usr/bin/env python3
"""Generate a C header embedding Lua scripts and binary assets.

Usage: gen_embed.py -o out.h name=path [name=path ...]
"""
import argparse
import os
import sys


def emit(f, name, data):
    f.write("static const unsigned char %s[] = {\n" % name)
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        f.write("  " + ", ".join("0x%02x" % b for b in chunk) + ",\n")
    f.write("};\n")
    f.write("static const unsigned int %s_len = %d;\n\n" % (name, len(data)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--output", required=True)
    ap.add_argument("inputs", nargs="+", help="name=path")
    args = ap.parse_args()

    pairs = []
    for item in args.inputs:
        if "=" not in item:
            sys.exit("bad input (want name=path): %s" % item)
        name, path = item.split("=", 1)
        if not name.isidentifier():
            sys.exit("bad C identifier: %s" % name)
        with open(path, "rb") as f:
            pairs.append((name, f.read()))

    tmp = args.output + ".tmp"
    with open(tmp, "w") as f:
        f.write("/* generated by gen_embed.py; do not edit */\n")
        f.write("#ifndef MYAGENT_EMBED_H\n#define MYAGENT_EMBED_H\n\n")
        for name, data in pairs:
            emit(f, name, data)
        f.write("#endif\n")
    os.replace(tmp, args.output)


if __name__ == "__main__":
    main()
